/**
 * Rule: Auto-number new rows.
 *
 * Gives an integer ID column an identity default and moves its sequence past the highest
 * existing value, so a row added without an ID gets the next number. Fixes tables whose primary
 * key was created with no default (every gis-publish table before the identity change — G12 on
 * the Land Bank site).
 *
 * Removing the rule keeps the default: dropping it would break adding rows. Drop it by hand if
 * that's really wanted (ALTER TABLE … ALTER COLUMN … DROP IDENTITY).
 */
const { qualified, quoteIdent } = require('./sql');
const { findColumn } = require('./introspect');

const hasAutoDefault = (col) => !!col && (col.isIdentity || /^nextval\(/i.test(col.default || ''));

module.exports = {
  label: 'Auto-number new rows',
  description: 'Gives the ID column a default, so each new row gets the next number when it is added.',
  removeNote: 'The ID column keeps its default, so adding rows keeps working.',
  params: [
    { name: 'column', type: 'column', columnKinds: ['integer'], label: 'ID column', defaultFrom: 'primaryKey' },
  ],

  appliesTo: (info) => info.columns.some(c => c.kind === 'integer'),

  normalize: ({ info, params }) => ({ column: params.column || info.pk || undefined }),

  key: (params) => `auto_number:${params.column}`,

  validate({ info, params }) {
    if (!params.column) throw new Error('Pick the ID column to number.');
    const col = findColumn(info, params.column);
    if (!col) throw new Error(`Column "${params.column}" does not exist on ${info.schema}.${info.table}.`);
    if (col.kind !== 'integer') {
      throw new Error(`Auto-number needs a whole-number column; "${col.name}" is ${col.udt}.`);
    }
    if (hasAutoDefault(col)) return; // already numbered: attaching just records it
    if (col.default != null) {
      throw new Error(`"${col.name}" already has a default (${col.default}). Remove it before using Auto-number.`);
    }
    if (!col.notNull) {
      throw new Error(`"${col.name}" allows empty values. Make it the primary key first (Metadata page).`);
    }
  },

  install({ info, params }) {
    const col = findColumn(info, params.column);
    if (hasAutoDefault(col)) return [];
    const t = qualified(info.schema, info.table);
    const c = quoteIdent(params.column);
    return [
      `ALTER TABLE ${t} ALTER COLUMN ${c} ADD GENERATED BY DEFAULT AS IDENTITY`,
      {
        text: `SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT max(${c}) FROM ${t}), 0) + 1, false)`,
        values: [t, params.column],
      },
    ];
  },

  uninstall: () => [],

  status: ({ info, params }) => (hasAutoDefault(findColumn(info, params.column)) ? 'installed' : 'missing'),
};
